/**
 * core/deploy/launcher.js
 *
 * The small script PM2 runs when an app's start command is a command line
 * (`npm start`, `python app.py`, `./server --port 3000`) rather than a plain
 * `node file.js`.
 *
 * PM2 starts a script, not a command line. Asking it to run `npm` directly
 * works on Linux and fails on Windows, where `npm` is `npm.cmd`; wrapping the
 * command in a shell means choosing that shell per platform in a PM2 config.
 * This file sidesteps both: PM2 always runs `node ez-launch.cjs`, and Node's
 * own `shell: true` picks `/bin/sh` or `cmd.exe`.
 *
 * It is written into each release directory by the engine. It is CommonJS
 * (.cjs) on purpose, so it runs the same whether or not the deployed project
 * declares `"type": "module"`.
 *
 * Not project code in the sense of CLAUDE.md's "only core/shell.js spawns":
 * this runs inside the DEPLOYED app's process tree, under PM2, and never
 * inside Easy DevOps.
 */

export const LAUNCHER_FILE = 'ez-launch.cjs';

/** Environment variable the launcher reads its command from. */
export const LAUNCHER_COMMAND_ENV = 'EZ_START_COMMAND';

export const LAUNCHER_SOURCE = `// Generated by Easy DevOps. Starts the app's command line under PM2.
'use strict';
const { spawn } = require('child_process');

const command = process.env.${LAUNCHER_COMMAND_ENV};
if (!command) {
  console.error('[ez-launch] ${LAUNCHER_COMMAND_ENV} is not set - nothing to start.');
  process.exit(1);
}

const child = spawn(command, { shell: true, stdio: 'inherit', windowsHide: true });

// PM2 stops an app by signalling this process. Pass it on, so the real app
// gets the chance to shut down cleanly instead of being orphaned.
for (const signal of ['SIGINT', 'SIGTERM', 'SIGHUP']) {
  process.on(signal, () => {
    try { child.kill(signal); } catch (_) { /* already gone */ }
  });
}

child.on('error', (err) => {
  console.error('[ez-launch] could not start: ' + err.message);
  process.exit(1);
});

// Exit the way the app did, so PM2's restart policy sees the real outcome.
child.on('exit', (code, signal) => {
  process.exit(signal ? 1 : (code === null ? 1 : code));
});
`;
